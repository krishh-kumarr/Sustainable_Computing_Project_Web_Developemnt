/**
 * Sustainability Advisor types.
 *
 * The advisor is a **rule-based recommendation engine**, not a language model.
 * There is no LLM integration in this application, and nothing the advisor
 * produces is ever presented as a generated answer. Every finding states the
 * rule that produced it and shows the arithmetic behind its numbers.
 *
 * The important design decision: a recommendation's quantified benefit is
 * never asserted. It is measured by running the simulation engine again with
 * the proposed parameter change and comparing complete runs. If the measured
 * benefit is negligible, the rule withholds the recommendation rather than
 * making it anyway.
 */

import type { MetricValues, ScenarioRun } from '../types/engine.ts'
import type { ParameterValues } from '../types/parameters.ts'

export type FindingKind =
  /** A change that improves at least one metric with no metric worsening. */
  | 'opportunity'
  /** A change that improves some metrics and worsens others. */
  | 'trade-off'
  /** Something about the current configuration worth knowing. */
  | 'observation'
  /** A current setting producing a materially bad outcome. */
  | 'caution'
  /** A limit of the data or the model that affects how results should be read. */
  | 'limitation'

export interface FindingMagnitude {
  label: string
  /** Signed change, alternative minus current. */
  value: number
  unit: string
  decimals: number
  /** Signed percentage change, where the current value is non-zero. */
  percent: number | null
  /** True when this direction of change is an improvement. */
  isImprovement: boolean
}

export interface AdvisorFinding {
  id: string
  kind: FindingKind
  title: string
  /** The recommendation or observation itself, with its computed figures. */
  detail: string
  /**
   * Why this appeared: the rule, its trigger condition, and the arithmetic.
   * Shown in the interface, because a recommendation a reader cannot audit is
   * just an assertion.
   */
  basis: string
  /** Quantified effects, measured by re-running the engine. */
  magnitudes: FindingMagnitude[]
  /** Parameter changes that would apply this recommendation. */
  action?: { label: string; overrides: ParameterValues }
  /** Rank for ordering; higher is more significant. */
  weight: number
}

export interface AdvisorContext {
  engineId: string
  engineLabel: string
  params: ParameterValues
  metrics: MetricValues
  /** The current parameters run to completion. */
  currentRun: ScenarioRun
  /** A saved baseline, if the user captured one. */
  baselineRun: ScenarioRun | null
  /** Human-readable location, for findings that mention it. */
  locationLabel: string
  /** Whether the engine's baseline was seeded from real observations. */
  seededFromObservation: boolean
  /** Provenance lines from the engine baseline. */
  provenance: string[]
  /**
   * Runs the engine with the given overrides and returns the resulting
   * metrics. This is how every quantified claim in a finding is produced.
   */
  evaluate: (overrides: ParameterValues) => MetricValues
}

export type AdvisorRule = (context: AdvisorContext) => AdvisorFinding | null

export interface AdvisorReport {
  engineId: string
  findings: AdvisorFinding[]
  /** Statement of what produced this report. Rendered verbatim in the UI. */
  method: string
  generatedAt: string
}

